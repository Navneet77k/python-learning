def conditional_examples():
    # Example of if statement
    num = 10
    if num > 0:
        print(f"{num} is positive")
    
    # Example of if-else statement
    num = -5
    if num > 0:
        print(f"{num} is positive")
    else:
        print(f"{num} is negative")
    
    # Example of if-elif-else statement
    num = 0
    if num > 0:
        print(f"{num} is positive")
    elif num < 0:
        print(f"{num} is negative")
    else:
        print(f"{num} is zero")

conditional_examples()